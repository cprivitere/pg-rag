"""Contracts the tool-corpus build: its freshness refusal and its build lock.

``data/tool_documents.json`` is derived from ``data/documents.json``, so
building it from a documents file generated by another ``DOCUMENTS_VERSION``
must abort with a clear message instead of shipping a corpus rendered by an
older generator. This is the old build-index staleness refusal, ported to the
artifact that now consumes documents.json.

The derive is also a corpus write, so it holds the cross-instance build lock
(``pgrag.buildlock``) for its duration: a peer's live lock in the artifact
directory must abort the run before any output is written.
"""

import json
import os
import time

import pytest

import scripts.build_tool_corpus as btc
from pgrag import buildlock


def _wire(tmp_path, monkeypatch, *, docs: bool, stamp):
    src = tmp_path / "documents.json"
    if docs:
        src.write_text("[]", encoding="utf-8")
    stamp_file = tmp_path / "documents_version.json"
    if stamp is not None:
        stamp_file.write_text(json.dumps({"version": stamp}), encoding="utf-8")
    monkeypatch.setattr(btc, "SRC", src)
    monkeypatch.setattr(btc, "DOCUMENTS_VERSION_FILE", stamp_file)


def test_accepts_current_document_version(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION)
    btc._require_fresh_documents()  # no raise


def test_refuses_stale_document_version(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION - 1)
    with pytest.raises(SystemExit, match="generated by document version"):
        btc._require_fresh_documents()


def test_refuses_missing_documents(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=False, stamp=btc.DOCUMENTS_VERSION)
    with pytest.raises(SystemExit, match="missing"):
        btc._require_fresh_documents()


def test_refuses_missing_version_stamp(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=None)
    with pytest.raises(SystemExit, match="is stamped"):
        btc._require_fresh_documents()


def test_main_refuses_while_a_peer_holds_the_build_lock(tmp_path, monkeypatch):
    """A live peer lock in the artifact dir aborts the derive before it writes
    anything (the writers own the lock; the pre-hook only probes it)."""
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION)
    out = tmp_path / "tool_documents.json"
    monkeypatch.setattr(btc, "OUT", out)
    monkeypatch.setattr(btc, "PKL", tmp_path / "tool_bm25.pkl")
    buildlock.lock_path(tmp_path).write_text(
        json.dumps({"pid": os.getpid(), "startedAt": int(time.time() * 1000)})
    )

    with pytest.raises(buildlock.BuildLocked):
        btc.main()
    assert not out.exists(), "derived over a peer's lock"
