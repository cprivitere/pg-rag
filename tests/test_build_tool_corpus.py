"""Contracts the tool-corpus build: its freshness refusal and its build lock.

``data/tool_documents.json`` is derived from ``data/documents.json``, so
building it from a documents file generated by another ``DOCUMENTS_VERSION``
must abort with a clear message instead of shipping a corpus rendered by an
older generator. This is the old build-index staleness refusal, ported to the
artifact that now consumes documents.json.

The derive is also a corpus write, so it holds the cross-instance build lock
(``pgrag.buildlock``) for its duration: a peer's live lock in the artifact
directory must abort the run before any output is written.

The stamp is a *pair* with the corpus it guards: both are addressed from the
CWD (as ``SRC``/``OUT``/``PKL`` are), so a CWD-rooted data tree — the molab
sandbox's ``corpus_docs`` cell, whose package lives in ``pg-rag-src/`` — builds
instead of aborting on a stamp looked up under the imported package root. The
refusal also runs BEFORE the lock: a stale tree fails fast without touching it.
"""

import json
import os
import subprocess
import sys
import time
from pathlib import Path

import pytest

import scripts.build_tool_corpus as btc
from pgrag import buildlock


def _wire(tmp_path, monkeypatch, *, docs: bool, stamp):
    src = tmp_path / "documents.json"
    if docs:
        src.write_text("[]", encoding="utf-8")
    stamp_file = tmp_path / "documents_version.json"
    if stamp is not None:
        stamp_file.write_text(json.dumps({"version": stamp}), encoding="utf-8")
    monkeypatch.setattr(btc, "SRC", src)
    monkeypatch.setattr(btc, "DOCUMENTS_VERSION_FILE", stamp_file)


def test_accepts_current_document_version(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION)
    btc._require_fresh_documents()  # no raise


def test_refuses_stale_document_version(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION - 1)
    with pytest.raises(SystemExit, match="generated by document version"):
        btc._require_fresh_documents()


def test_refuses_missing_documents(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=False, stamp=btc.DOCUMENTS_VERSION)
    with pytest.raises(SystemExit, match="missing"):
        btc._require_fresh_documents()


def test_refuses_missing_version_stamp(tmp_path, monkeypatch):
    _wire(tmp_path, monkeypatch, docs=True, stamp=None)
    with pytest.raises(SystemExit, match="is stamped"):
        btc._require_fresh_documents()


def test_main_refuses_while_a_peer_holds_the_build_lock(tmp_path, monkeypatch):
    """A live peer lock in the artifact dir aborts the derive before it writes
    anything (the writers own the lock; the pre-hook only probes it)."""
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION)
    out = tmp_path / "tool_documents.json"
    monkeypatch.setattr(btc, "OUT", out)
    monkeypatch.setattr(btc, "PKL", tmp_path / "tool_bm25.pkl")
    buildlock.lock_path(tmp_path).write_text(
        json.dumps({"pid": os.getpid(), "startedAt": int(time.time() * 1000)})
    )

    with pytest.raises(buildlock.BuildLocked):
        btc.main()
    assert not out.exists(), "derived over a peer's lock"


def test_main_checks_freshness_before_the_lock(tmp_path, monkeypatch):
    """contract: the freshness refusal runs BEFORE `corpus_lock`.

    A stale tree cannot produce output, so it must fail fast on the stamp
    instead of queueing behind (or aborting inside) a peer's build — the
    stamp is checked first, so the peer's lock is never even consulted.
    """
    _wire(tmp_path, monkeypatch, docs=True, stamp=btc.DOCUMENTS_VERSION - 1)
    buildlock.lock_path(tmp_path).write_text(
        json.dumps({"pid": os.getpid(), "startedAt": int(time.time() * 1000)})
    )

    with pytest.raises(SystemExit, match="generated by document version"):
        btc.main()


def test_builds_against_a_cwd_rooted_data_tree(tmp_path):
    """End-to-end contract (the molab failure mode): the version stamp is
    addressed from the CWD, like documents.json/OUT/PKL themselves.

    The molab sandbox keeps the corpus and its stamp as a CWD-rooted pair
    (`data/documents.json` + `data/derived/documents_version.json`, written by
    the `corpus_docs` cell) while the package lives in `pg-rag-src/`;
    anchoring the stamp at the imported package root looked for
    `pg-rag-src/data/derived/documents_version.json` and aborted every build
    with "missing — run `mise generate-docs`". A real subprocess with
    `cwd=tmp_path` is the only faithful check: in-process tests monkeypatch the
    module globals and so never exercise the package-root anchor.
    (In this repo the anchored candidate happens to exist and match, so the
    sibling `test_the_cwd_stamp_is_the_one_consulted` is what pins the anchor
    on a healthy checkout.)
    """
    repo = Path(__file__).resolve().parents[1]
    data = tmp_path / "data"
    (data / "derived").mkdir(parents=True)
    (data / "documents.json").write_text(
        json.dumps(
            [
                {"id": "wiki_1", "text": "alpha beta", "metadata": {"table": "wiki"}},
                {"id": "recipe_1", "text": "butter churn", "metadata": {"table": "recipes"}},
                # Dropped by the stage-1 list: the derive must be real work.
                {"id": "item_1", "text": "spider silk", "metadata": {"table": "items"}},
            ]
        ),
        encoding="utf-8",
    )
    (data / "derived" / "documents_version.json").write_text(
        json.dumps({"version": btc.DOCUMENTS_VERSION}), encoding="utf-8"
    )

    proc = subprocess.run(
        [sys.executable, str(repo / "scripts" / "build_tool_corpus.py")],
        cwd=tmp_path,
        capture_output=True,
        text=True,
    )

    assert proc.returncode == 0, proc.stderr
    kept = json.loads((data / "tool_documents.json").read_text(encoding="utf-8"))
    assert [d["id"] for d in kept] == ["wiki_1", "recipe_1"]
    assert (data / "tool_bm25.pkl").exists()
    # And it locked the CWD tree, not the repo's: no stray lock is left behind.
    assert not (data / ".omp-build.lock").exists()


def test_the_cwd_stamp_is_the_one_consulted(tmp_path):
    """The anchor fix, made observable: a CWD stamp of another version refuses.

    The two candidate stamps must *disagree* for the addressing to be visible,
    and a healthy checkout satisfies exactly that: the package-anchored path
    (`<package root>/data/derived/documents_version.json`) exists and matches
    the current DOCUMENTS_VERSION, so pre-fix this run would have read *that*
    stamp, found it fresh and written the corpus anyway — the CWD tree's own
    stamp was never consulted.
    """
    repo = Path(__file__).resolve().parents[1]
    data = tmp_path / "data"
    (data / "derived").mkdir(parents=True)
    (data / "documents.json").write_text(
        json.dumps([{"id": "wiki_1", "text": "alpha beta", "metadata": {"table": "wiki"}}]),
        encoding="utf-8",
    )
    (data / "derived" / "documents_version.json").write_text(
        json.dumps({"version": btc.DOCUMENTS_VERSION - 1}), encoding="utf-8"
    )

    proc = subprocess.run(
        [sys.executable, str(repo / "scripts" / "build_tool_corpus.py")],
        cwd=tmp_path,
        capture_output=True,
        text=True,
    )

    assert proc.returncode != 0, "built from a stamp it was never pointed at"
    assert "generated by document version" in proc.stderr
    assert not (data / "tool_documents.json").exists()
